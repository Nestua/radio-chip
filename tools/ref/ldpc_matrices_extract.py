"""Transcribe the LDPC matrix prototypes of IEEE Std 802.11-2024 Annex F (Tables F-1 … F-3)
from your own copy of the standard into crates/radio-phy/src/ldpc_tables.rs.

The prototypes are parameters of the protocol: without them an encoder does not interoperate.
They are in the repository with the clause cited (ADR 0005, addendum 2026-11-19); the
standard's text is not. A script does the transcription so that no digit is typed by hand;
the result is checked against references that do not come from this script
(crates/radio-phy/tests/g1_ldpc.rs).

    pdftotext -layout 80211-2024.pdf 80211-2024.txt        (brew install poppler)
    python3 -I tools/ref/ldpc_matrices_extract.py 80211-2024.txt crates/radio-phy/src/ldpc_tables.rs
"""

import re
import sys

TABLE = re.compile(r"^\s*Table F-([123])—Matrix prototypes for codeword block length n = (\d+) bits,")
RATE = re.compile(r"^\s*\(([abcd])\) Coding rate R = (\d)/(\d)\.")
ROW = re.compile(r"^\s*((?:\d+|-)(?:\s+(?:\d+|-)){23})\s*$")
ROWS = {"a": 12, "b": 8, "c": 6, "d": 4}


def main(src, dst):
    lines = open(src, encoding="utf-8").read().replace("–", "-").replace("−", "-").splitlines()
    # The body of Annex F (the table of contents lists the tables too, with leader dots).
    start = next(i for i, l in enumerate(lines) if l.strip() == "HT LDPC matrix definitions")
    codes, table, rate = {}, None, None
    for line in lines[start:]:
        if m := TABLE.match(line):
            table = int(m.group(2))
        elif m := RATE.match(line):
            rate = m.group(1)
            codes[(table, rate)] = []
        elif (m := ROW.match(line)) and table and rate and len(codes[(table, rate)]) < ROWS[rate]:
            codes[(table, rate)].append([-1 if t == "-" else int(t) for t in m.group(1).split()])
        if len(codes) == 12 and all(len(codes[k]) == ROWS[k[1]] for k in codes):
            break
    assert sorted(codes) == [(n, r) for n in (648, 1296, 1944) for r in "abcd"], sorted(codes)
    for (n, r), rows in codes.items():
        z = n // 24
        assert len(rows) == ROWS[r] and all(len(row) == 24 for row in rows), (n, r)
        assert all(-1 <= v < z for row in rows for v in row), (n, r)

    out = [
        "//! LDPC matrix prototypes of IEEE Std 802.11-2024 Annex F, Tables F-1 … F-3 (HT LDPC",
        "//! matrix definitions; used by §19.3.11.7).",
        "//!",
        "//! GENERATED by `tools/ref/ldpc_matrices_extract.py` from a copy of the standard: do not",
        "//! edit by hand. Each entry is the cyclic shift of a Z × Z identity block, −1 the zero block.",
        "",
        "/// Prototype rows (24 columns each) by block length (648, 1296, 1944 bits: Z = 27, 54, 81)",
        "/// and by rate (1/2, 2/3, 3/4, 5/6: 12, 8, 6, 4 rows).",
        "#[rustfmt::skip]",
        "pub(crate) const PROTOTYPES: [[&[[i8; 24]]; 4]; 3] = [",
    ]
    for n in (648, 1296, 1944):
        out.append(f"    // Table F-{(648, 1296, 1944).index(n) + 1}: n = {n}, Z = {n // 24}")
        out.append("    [")
        for r, name in zip("abcd", ("1/2", "2/3", "3/4", "5/6")):
            out.append(f"        // ({r}) R = {name}")
            out.append("        &[")
            for row in codes[(n, r)]:
                out.append("            [" + ", ".join(f"{v:2d}" for v in row) + "],")
            out.append("        ],")
        out.append("    ],")
    out.append("];")
    open(dst, "w", encoding="utf-8").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
